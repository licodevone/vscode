import { existsSync, readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, delimiter, extname, join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const begin = '# BEGIN ACMEBR MANAGED MCP';
const end = '# END ACMEBR MANAGED MCP';
const read = path => readFileSync(join(root, path), 'utf8').replace(/\r\n/g, '\n');
const quote = value => JSON.stringify(value);

function frontmatter(path) {
	const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(read(path));
	if (!match) {
		throw new Error(`Frontmatter ausente: ${path}`);
	}
	const fields = {};
	for (const line of match[1].split('\n')) {
		const field = /^([a-z-]+):\s*(.+)$/.exec(line);
		if (!field) {
			throw new Error(`Campo inválido: ${path}: ${line}`);
		}
		fields[field[1]] = JSON.parse(field[2]);
	}
	if (!fields.name || !fields.description) {
		throw new Error(`name e description são obrigatórios: ${path}`);
	}
	return { ...fields, body: match[2].trim() };
}

function files(path, suffix) {
	return readdirSync(join(root, path)).filter(name => name.startsWith('acmebr-') && name.endsWith(suffix)).sort();
}

function generatedFiles() {
	const generated = new Map();
	for (const file of files('docs/prompts', '.prompt.md')) {
		generated.set(`.github/prompts/${file}`, read(`docs/prompts/${file}`));
	}
	for (const file of files('.github/agents', '.agent.md')) {
		const role = frontmatter(`.github/agents/${file}`);
		if (role.body.includes("'''")) {
			throw new Error(`Aspas TOML reservadas no agente: ${file}`);
		}
		generated.set(`.codex/agents/${role.name}.toml`, `# Generated by pnpm agent:sync from .github/agents/${file}\nname = ${quote(role.name)}\ndescription = ${quote(role.description)}\ndeveloper_instructions = '''\n${role.body}\n'''\n`);
	}

	const servers = JSON.parse(read('.mcp.json')).mcpServers;
	if (!servers || Object.keys(servers).length === 0) {
		throw new Error('Nenhum MCP definido em .mcp.json');
	}
	const vscode = {};
	const toml = [begin, '# Source: .mcp.json. Run pnpm agent:sync after editing.'];
	for (const [name, server] of Object.entries(servers)) {
		toml.push('', `[mcp_servers.${quote(name)}]`);
		if (server.type === 'http') {
			if (!server.url || new URL(server.url).protocol !== 'https:') {
				throw new Error(`MCP HTTP deve declarar URL HTTPS: ${name}`);
			}
			vscode[name] = { type: 'http', url: server.url };
			toml.push(`url = ${quote(server.url)}`);
		} else if (server.type === 'stdio') {
			if (typeof server.command !== 'string' || !Array.isArray(server.args) || server.args.some(arg => typeof arg !== 'string')) {
				throw new Error(`Comando stdio inválido: ${name}`);
			}
			vscode[name] = { ...server, cwd: '${workspaceFolder}' };
			toml.push(`command = ${quote(server.command)}`, `args = ${quote(server.args)}`, 'startup_timeout_sec = 60');
		} else {
			throw new Error(`Transporte não suportado: ${name}`);
		}
		const supported = server.type === 'http' ? ['type', 'url'] : ['type', 'command', 'args'];
		if (Object.keys(server).some(key => !supported.includes(key))) {
			throw new Error(`MCP ${name}: estenda o gerador antes de adicionar novos campos para não perdê-los nos adaptadores.`);
		}
	}

	generated.set('.vscode/mcp.json', `${JSON.stringify({ servers: vscode }, null, '\t')}\n`);
	const path = '.codex/config.toml';
	const current = existsSync(join(root, path)) ? read(path) : '# ACME BR IDE: project-scoped configuration.\n# Personal settings may be added outside the managed block.\n';
	const block = `${toml.join('\n')}\n${end}`;
	const startIndex = current.indexOf(begin);
	const endIndex = current.indexOf(end);
	if ((startIndex === -1) !== (endIndex === -1) || (startIndex !== -1 && endIndex < startIndex)) {
		throw new Error('Bloco gerado incompleto em .codex/config.toml');
	}
	const config = startIndex === -1 ? `${current.trimEnd()}\n\n${block}\n` : current.slice(0, startIndex) + block + current.slice(endIndex + end.length);
	generated.set(path, config);
	return generated;
}

function sync(check) {
	const drift = [];
	for (const [path, expected] of generatedFiles()) {
		if (existsSync(join(root, path)) && read(path) === expected) {
			continue;
		}
		if (check) {
			drift.push(path);
		} else {
			mkdirSync(dirname(join(root, path)), { recursive: true });
			writeFileSync(join(root, path), expected);
			console.log(`Gerado: ${path}`);
		}
	}
	if (drift.length) {
		throw new Error(`Adaptadores desatualizados: ${drift.join(', ')}. Execute pnpm agent:sync.`);
	}
}

function check() {
	sync(true);
	const agents = new Set(files('.github/agents', '.agent.md').map(file => frontmatter(`.github/agents/${file}`).name));
	for (const file of files('.codex/agents', '.toml')) {
		if (!agents.has(basename(file, '.toml'))) {
			throw new Error(`Adaptador sem agente fonte: .codex/agents/${file}`);
		}
	}
	const skills = files('.agents/skills', '');
	for (const name of skills) {
		const skill = frontmatter(`.agents/skills/${name}/SKILL.md`);
		if (skill.name !== name || !/^[a-z0-9-]{1,64}$/.test(name)) {
			throw new Error(`Nome de skill inválido: ${name}`);
		}
	}
	const prompts = files('docs/prompts', '.prompt.md');
	for (const file of prompts) {
		const path = `docs/prompts/${file}`;
		const prompt = frontmatter(path);
		if (!agents.has(prompt.agent)) {
			throw new Error(`Agente não encontrado para ${file}: ${prompt.agent}`);
		}
		for (const link of prompt.body.matchAll(/\]\(([^)]+)\)/g)) {
			if (!existsSync(resolve(root, dirname(path), link[1]))) {
				throw new Error(`Referência inexistente em ${file}: ${link[1]}`);
			}
		}
	}
	for (const path of ['AGENTS.md', 'docs/agent-environment.md', 'docs/product-direction.md', 'docs/cursor-parity.md', 'scripts/acmebr-mcp-smoke.py']) {
		if (!existsSync(join(root, path))) {
			throw new Error(`Arquivo necessário ausente: ${path}`);
		}
	}
	console.log(`Ambiente consistente: ${agents.size} agentes, ${skills.length} skills, ${prompts.length} comandos e ${Object.keys(JSON.parse(read('.mcp.json')).mcpServers).length} MCPs.`);
}

function executable(command) {
	const extensions = process.platform === 'win32' ? ['.exe', '.com', '.cmd', '.bat'] : [''];
	for (const folder of (process.env.PATH ?? '').split(delimiter).filter(Boolean)) {
		for (const extension of extensions) {
			const candidate = join(folder.replace(/^"|"$/g, ''), command + extension);
			if (existsSync(candidate)) {
				return candidate;
			}
		}
	}
	return undefined;
}

function doctor() {
	const expectedNode = read('.nvmrc').trim();
	const expectedPnpm = JSON.parse(read('package.json')).packageManager;
	console.log(`Raiz: ${root}`);
	console.log(`[${process.versions.node === expectedNode ? 'OK' : 'ATENÇÃO'}] Node ${process.versions.node}; .nvmrc: ${expectedNode}`);
	let missing = process.versions.node !== expectedNode;
	for (const command of ['pnpm', 'git', 'python', 'codex']) {
		const path = executable(command);
		const required = command === 'pnpm' || command === 'git';
		missing ||= required && !path;
		let version = '';
		if (path && !['.cmd', '.bat'].includes(extname(path).toLowerCase())) {
			const result = spawnSync(path, ['--version'], { encoding: 'utf8', windowsHide: true, timeout: 10000 });
			version = result.status === 0 ? result.stdout.trim().split('\n')[0] : 'versão não detectada';
			if (command === 'pnpm' && version !== expectedPnpm.split('@')[1]) {
				console.log(`[ATENÇÃO] pnpm instalado: ${version}; packageManager: ${expectedPnpm}`);
				missing = true;
			}
		}
		console.log(`[${path ? 'OK' : required ? 'PENDENTE' : 'OPCIONAL'}] ${command}: ${path ?? 'não encontrado'}${version ? ` (${version})` : ''}`);
	}
	for (const [path, purpose] of [['node_modules', 'dependências do produto / component-explorer'], ['out/main.js', 'build do cliente Electron'], ['.build/electron', 'runtime Electron']]) {
		const ready = existsSync(join(root, path));
		missing ||= !ready;
		console.log(`[${ready ? 'OK' : 'PENDENTE'}] ${purpose}: ${path}`);
	}
	console.log('MCP playwright: pnpm dlx usa a versão fixada em .mcp.json; primeiro uso requer rede.');
	console.log('MCP openaiDeveloperDocs: requer rede. Doctor não comprova conexão MCP.');
	console.log('Para validar transporte e ferramentas: python scripts/acmebr-mcp-smoke.py playwright');
	if (process.argv.includes('--strict') && missing) {
		process.exitCode = 1;
	}
}

try {
	const command = process.argv[2] ?? 'check';
	switch (command) {
		case 'sync': sync(false); break;
		case 'check': check(); break;
		case 'doctor': doctor(); break;
		case 'command': {
			const name = process.argv[3];
			const available = files('docs/prompts', '.prompt.md').map(file => file.slice('acmebr-'.length, -'.prompt.md'.length));
			if (!available.includes(name)) {
				throw new Error(`Informe um comando: ${available.join(', ')}`);
			}
			const prompt = frontmatter(`docs/prompts/acmebr-${name}.prompt.md`);
			console.log(`Papel: ${prompt.agent}\nRaiz: ${root}\nFonte: docs/prompts/acmebr-${name}.prompt.md\n\n${prompt.body}`);
			break;
		}
		default: throw new Error('Uso: node scripts/acmebr-env.mjs <check|sync|doctor [--strict]|command nome>');
	}
} catch (error) {
	console.error(error.message);
	process.exitCode = 1;
}
